const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('nativeApp', {
  kbLoad: () => ipcRenderer.sendSync('kb-load'),
  kbSave: (data) => ipcRenderer.send('kb-save', data),
  copy: (text) => ipcRenderer.send('copy', text),
  save: (name, data) => ipcRenderer.invoke('save', name, data),
  pdf: (name, html) => ipcRenderer.invoke('pdf', name, html),
  scanFolder: (start) => ipcRenderer.invoke('scan-folder', start || ''),
  findLogs: () => ipcRenderer.invoke('find-logs'),
  readFile: (p) => ipcRenderer.invoke('read-file', p),
  openPath: (p) => ipcRenderer.send('open-path', p),
  updateInfo: () => ipcRenderer.invoke('update-info'),
  updateFromFile: () => ipcRenderer.invoke('update-from-file'),
  updateReset: () => ipcRenderer.invoke('update-reset'),
  gatedFetch: (p, o) => ipcRenderer.invoke('gated-fetch', p, o),
  shellInfo: () => ipcRenderer.invoke('shell-info'),
  watchInfo: () => ipcRenderer.invoke('watch-info'),
  watchSet: (m) => ipcRenderer.invoke('watch-set', m),
  onWatch: (cb) => ipcRenderer.on('watch-file', (e, d) => cb(d)),
  fetchUrl: (u) => ipcRenderer.invoke('fetch-url', u),
  updateCheck: (url, opts) => ipcRenderer.invoke('update-check', url === undefined ? null : url, opts || {}),
  updateApply: () => ipcRenderer.invoke('update-apply'),
  relaunch: () => ipcRenderer.invoke('app-relaunch'),
  shellPending: (v) => ipcRenderer.invoke('shell-pending', v || ''),
  reloadApp: () => ipcRenderer.invoke('app-reload'),
  appOk: (v) => ipcRenderer.send('app-ok', v || ''),
  extInfo: () => ipcRenderer.invoke('ext-info'),
  extReset: () => ipcRenderer.invoke('ext-reset'),
  onExtImport: (cb) => ipcRenderer.on('ext-import', (e, d) => cb(d)),
  extReady: () => ipcRenderer.send('ext-ready')
});
