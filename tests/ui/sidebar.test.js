// Левая панель «Логи»: своя папка, переименование, перетаскивание лога в папку, поиск, удаление папки, скрытие панели.
const H = require('./helpers'), { ok } = H;
(async () => {
  const { b, p, errs } = await H.launch(1400, 1000);
  await H.load(p, [H.mainLog('s1.log', { attempts: ['fail'] })]); await H.load(p, [H.clientLog('client_2026-10-06_09-00-00.log', { crash: true })]);
  ok(await p.locator('#side #flist > li > .fi.file').count() === 2, 'логи в левой панели');
  await p.click('[data-act=newFolder]'); await p.waitForTimeout(400);
  ok(await p.evaluate(() => document.activeElement && document.activeElement.id === 'gName' && /^Новая папка/.test(document.activeElement.value)), 'новая папка создана, курсор в названии');
  await p.fill('#gName', 'Тикет 555'); await p.press('#gName', 'Enter'); await p.waitForTimeout(300);
  ok(await p.locator('#flist .fi.folder .nm:has-text("Тикет 555")').count() === 1 && await p.locator('#flist .fi.folder.empty').count() === 1, 'пустая папка с моим названием');
  ok(await p.locator('#flist .fdraw .fd-empty').count() === 1, 'в пустой папке подсказка, куда тащить');
  await p.locator('#flist > li > .fi.file >> nth=0').dragTo(p.locator('#flist .fi.folder')); await p.waitForTimeout(400);
  ok(await p.locator('#flist .fdraw .fi.file').count() === 1 && await p.textContent('#flist .fi.folder .fcnt') === '1', 'лог перетащен в свою папку');
  await p.click('#flist .fi.folder'); await p.waitForTimeout(400);
  ok(await p.locator('#flist .fdraw').count() === 0 && await p.locator('#flist .fi.folder:not(.open)').count() === 1, 'папка закрывается щелчком');
  await p.click('#flist .fi.folder'); await p.waitForTimeout(60);
  ok(await p.locator('#flist .fdraw.enter').count() === 1, 'папка открывается с анимацией');
  await p.reload(); await p.waitForTimeout(2500);
  ok(await p.locator('#flist .fi.folder .nm:has-text("Тикет 555")').count() === 1, 'своя папка сохраняется после перезапуска');
  await p.fill('#sideQ', '09-00'); await p.waitForTimeout(300);
  ok(await p.locator('#side .fi.file').count() === 1 && await p.locator('#side .fdraw .fi.file').count() === 1 && !(await p.locator('#side .nm:has-text("s1.log")').count()), 'поиск оставляет подходящий лог и раскрывает его папку');
  await p.fill('#sideQ', 'тикет'); await p.waitForTimeout(300);
  ok(await p.locator('#side .fi.folder').count() === 1, 'поиск находит папку по названию');
  await p.fill('#sideQ', ''); await p.waitForTimeout(200);
  if (!(await p.locator('#flist .fdraw').count())) await p.click('#flist .fi.folder');
  await p.waitForTimeout(300);
  await p.click('#flist [data-act=gdel]'); await p.waitForTimeout(300);
  ok(await p.locator('#flist .fi.folder').count() === 0 && await p.locator('#flist > li > .fi.file').count() === 2, 'удаление папки оставляет логи в списке');
  await p.click('#actHd [data-act=undo]'); await p.waitForTimeout(300);
  ok(await p.locator('#flist .fi.folder .nm:has-text("Тикет 555")').count() === 1, 'удаление папки отменяется');
  await p.click('#side [data-act=sideToggle]'); await p.waitForTimeout(200);
  ok(!(await p.isVisible('#side')) && await p.isVisible('.side-rail'), 'панель скрывается, остаётся узкая полоса');
  await p.click('.side-rail'); await p.waitForTimeout(200);
  ok(await p.isVisible('#side'), 'панель возвращается');
  await p.keyboard.press('Control+Shift+KeyN'); await p.waitForTimeout(300);
  ok(await p.evaluate(() => document.activeElement && document.activeElement.id === 'gName'), 'Ctrl+Shift+N создаёт папку');
  await p.keyboard.press('Escape'); await p.waitForTimeout(200);
  await H.done(b, errs);
})();
